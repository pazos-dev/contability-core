// Regenerates src/core/domain/money/currency-catalog.ts from the official ISO 4217 list.
// Usage:
//   pnpm sync:iso4217                        download the current list from SIX Group
//   pnpm sync:iso4217 --input <file.xml>     use a previously downloaded copy
// The generated table is the canonical runtime data; never edit it by hand.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const SOURCE_URL =
  'https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml';
const OUTPUT = fileURLToPath(new URL('../src/core/domain/money/currency-catalog.ts', import.meta.url));
const NO_MINOR_UNIT = 'N.A.';
const NO_UNIVERSAL_CURRENCY = 'No universal currency';
const UNITS_PATTERN = /^(?:N\.A\.|[0-6])$/;
const DOCUMENT_END = '</ISO_4217>';
// The ISO 4217 list has never carried fewer than ~160 decimal currencies. A table far below that
// means a mutilated source, not a currency reform; a plausible-but-incomplete table must not ship.
const MIN_DECIMAL_CURRENCIES = 100;

function fail(message) {
  console.error(message);
  process.exit(1);
}

// Byte-order comparison so regeneration does not depend on the ICU locale.
function byCodePoint(left, right) {
  if (left < right) return -1;
  return left > right ? 1 : 0;
}

async function loadXml() {
  const inputIndex = process.argv.indexOf('--input');
  if (inputIndex === -1) {
    const response = await fetch(SOURCE_URL);
    if (!response.ok) fail(`No se pudo descargar la lista ISO 4217: HTTP ${response.status}`);
    return response.text();
  }

  const path = process.argv[inputIndex + 1];
  if (typeof path !== 'string' || path.length === 0) fail('--input requiere una ruta de archivo');
  return readFile(path, 'utf8');
}

function parse(xml) {
  // A download cut short keeps HTTP 200 and would otherwise emit a smaller, plausible table.
  if (!xml.trimEnd().endsWith(DOCUMENT_END)) {
    fail(`La lista está truncada: no termina en ${DOCUMENT_END}`);
  }

  const published = /<ISO_4217[^>]*\bPblshd="([^"]+)"/.exec(xml)?.[1];
  if (published === undefined) fail('La lista no declara la fecha de publicación (ISO_4217/@Pblshd)');

  const entries = [...xml.matchAll(/<CcyNtry>([\s\S]*?)<\/CcyNtry>/g)].map((match) => match[1]);
  if (entries.length === 0) fail('La lista no contiene entradas CcyNtry');

  const scales = new Map();
  const withoutMinorUnit = new Set();

  for (const entry of entries) {
    const name = /<CcyNm[^>]*>([^<]*)<\/CcyNm>/.exec(entry)?.[1]?.trim();
    const code = /<Ccy>([^<]+)<\/Ccy>/.exec(entry)?.[1];

    if (code === undefined) {
      // Territories without a currency of their own are legitimate; anything else is a defect.
      if (name === NO_UNIVERSAL_CURRENCY) continue;
      fail(`Entrada ISO 4217 sin código de moneda: ${name ?? 'sin CcyNm'}`);
    }

    const units = /<CcyMnrUnts>([^<]+)<\/CcyMnrUnts>/.exec(entry)?.[1];
    if (units === undefined) fail(`La entrada ${code} no declara unidad menor`);
    if (!UNITS_PATTERN.test(units)) fail(`Unidad menor no reconocida para ${code}: ${units}`);

    if (units === NO_MINOR_UNIT) {
      if (scales.has(code)) fail(`La moneda ${code} aparece con y sin unidad menor decimal`);
      withoutMinorUnit.add(code);
      continue;
    }

    if (withoutMinorUnit.has(code)) fail(`La moneda ${code} aparece con y sin unidad menor decimal`);

    const scale = Number(units);
    const known = scales.get(code);
    if (known !== undefined && known !== scale) {
      fail(`La moneda ${code} aparece con dos escalas distintas: ${known} y ${scale}`);
    }
    scales.set(code, scale);
  }

  if (scales.size < MIN_DECIMAL_CURRENCIES) {
    fail(
      `La tabla quedó incompleta: ${scales.size} monedas con escala decimal ` +
        `(mínimo esperado ${MIN_DECIMAL_CURRENCIES}). No se escribió el catálogo.`,
    );
  }

  return {
    published,
    scales: [...scales].sort(([left], [right]) => byCodePoint(left, right)),
    withoutMinorUnit: [...withoutMinorUnit].sort(byCodePoint),
  };
}

function render({ published, scales, withoutMinorUnit }, sha256) {
  const scaleLines = scales.map(([code, scale]) => `  ${code}: ${scale},`).join('\n');
  const withoutLines = withoutMinorUnit.map((code) => `  '${code}',`).join('\n');

  return `// Generated by scripts/sync-iso4217.mjs. Do not edit by hand.
// Source: ISO 4217 "list one" published by SIX Group, Pblshd ${published}.
// Source XML SHA-256: ${sha256}
// Regenerate with: pnpm sync:iso4217
//
// Only codes with a decimal minor unit carry a scale. Codes whose official minor unit is not a
// decimal scale (precious metals, SDR, testing and other non-decimal codes) are kept apart so the
// error can say why. The SHA-256 above is provenance, not a runtime check: the tripwire against an
// unintended table change is tests/currency-catalog.test.mjs (IC11), which pins the non-2 scales and
// the codes without a decimal minor unit. Changing them requires updating that test deliberately.

/** Publication date of the incorporated ISO 4217 list, as declared by its source. */
export const ISO_4217_PUBLISHED = '${published}';

/** One ISO 4217 currency with a decimal minor unit and its official scale. */
export interface IsoCurrencyEntry {
  readonly code: string;
  readonly scale: number;
}

const SCALES: Readonly<Record<string, number>> = Object.freeze({
${scaleLines}
});

const WITHOUT_MINOR_UNIT: ReadonlySet<string> = new Set([
${withoutLines}
]);

/** Official scale of an ISO 4217 code with a decimal minor unit; undefined otherwise. */
export function isoScaleOf(code: string): number | undefined {
  return Object.hasOwn(SCALES, code) ? SCALES[code] : undefined;
}

/** True when the code is ISO 4217 but declares no decimal minor unit. */
export function isoHasNoMinorUnit(code: string): boolean {
  return WITHOUT_MINOR_UNIT.has(code);
}

/** Every ISO 4217 currency with a decimal minor unit, ordered by code. */
export function listIsoCurrencies(): readonly IsoCurrencyEntry[] {
  return Object.entries(SCALES).map(([code, scale]) => ({ code, scale }));
}

/** Every ISO 4217 code without a decimal minor unit, ordered by code. */
export function listIsoCurrenciesWithoutMinorUnit(): readonly string[] {
  return [...WITHOUT_MINOR_UNIT].sort();
}
`;
}

const xml = await loadXml();
const table = parse(xml);
const sha256 = createHash('sha256').update(xml, 'utf8').digest('hex');

await writeFile(OUTPUT, render(table, sha256), 'utf8');

console.log(
  `ISO 4217 (publicada ${table.published}): ${table.scales.length} monedas con escala decimal, ` +
    `${table.withoutMinorUnit.length} sin unidad menor decimal.`,
);
console.log(`Escrito ${OUTPUT}`);
